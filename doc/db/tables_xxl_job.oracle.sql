-- —————————————————————— job group and registry ——————————————————

CREATE TABLE xxl_job_group
(
    id           NUMBER(11)     GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
    app_name     VARCHAR2(64)   NOT NULL,
    title        VARCHAR2(12)   NOT NULL,
    address_type NUMBER(4)      DEFAULT 0 NOT NULL,
    address_list VARCHAR2(4000),
    update_time  DATE,
    PRIMARY KEY (id)
);

COMMENT ON TABLE xxl_job_group IS '执行器';
COMMENT ON COLUMN xxl_job_group.id IS '执行器主键ID';
COMMENT ON COLUMN xxl_job_group.app_name IS '执行器AppName';
COMMENT ON COLUMN xxl_job_group.title IS '执行器名称';
COMMENT ON COLUMN xxl_job_group.address_type IS '执行器地址类型：0=自动注册、1=手动录入';
COMMENT ON COLUMN xxl_job_group.address_list IS '执行器地址列表，多地址逗号分隔';
COMMENT ON COLUMN xxl_job_group.update_time IS '更新时间';

CREATE TABLE xxl_job_registry
(
    id             NUMBER(11)    GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
    registry_group VARCHAR2(50)  NOT NULL,
    registry_key   VARCHAR2(255) NOT NULL,
    registry_value VARCHAR2(255) NOT NULL,
    update_time    DATE,
    PRIMARY KEY (id)
);

CREATE UNIQUE INDEX i_g_k_v ON xxl_job_registry (registry_group, registry_key, registry_value);

COMMENT ON TABLE xxl_job_registry IS '客户端注册';
COMMENT ON COLUMN xxl_job_registry.id IS '注册主键ID';
COMMENT ON COLUMN xxl_job_registry.registry_group IS '注册组';
COMMENT ON COLUMN xxl_job_registry.registry_key IS '注册主键';
COMMENT ON COLUMN xxl_job_registry.registry_value IS '注册值';
COMMENT ON COLUMN xxl_job_registry.update_time IS '更新时间';

-- —————————————————————— job info ——————————————————

CREATE TABLE xxl_job_info
(
    id                        NUMBER(11)     GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
    job_group                 NUMBER(11)     NOT NULL,
    job_desc                  VARCHAR2(255)  NOT NULL,
    add_time                  DATE,
    update_time               DATE,
    author                    VARCHAR2(64),
    alarm_email               VARCHAR2(255),
    schedule_type             VARCHAR2(50)   DEFAULT 'NONE' NOT NULL,
    schedule_conf             VARCHAR2(128),
    misfire_strategy          VARCHAR2(50)   DEFAULT 'DO_NOTHING' NOT NULL,
    executor_route_strategy   VARCHAR2(50),
    executor_handler          VARCHAR2(255),
    executor_param            VARCHAR2(512),
    executor_block_strategy   VARCHAR2(50),
    executor_timeout          NUMBER(11)     DEFAULT 0 NOT NULL,
    executor_fail_retry_count NUMBER(11)     DEFAULT 0 NOT NULL,
    glue_type                 VARCHAR2(50)   NOT NULL,
    glue_source               CLOB,
    glue_remark               VARCHAR2(128),
    glue_updatetime           DATE,
    child_jobid               VARCHAR2(255),
    trigger_status            NUMBER(4)      DEFAULT 0 NOT NULL,
    trigger_last_time         NUMBER(20)     DEFAULT 0 NOT NULL,
    trigger_next_time         NUMBER(20)     DEFAULT 0 NOT NULL,
    PRIMARY KEY (id)
);

