-- —————————————————————— job log and report ——————————————————

CREATE TABLE xxl_job_log
(
    id                        NUMBER(20)     GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
    job_group                 NUMBER(11)     NOT NULL,
    job_id                    NUMBER(11)     NOT NULL,
    executor_address          VARCHAR2(255),
    executor_handler          VARCHAR2(255),
    executor_param            VARCHAR2(512),
    executor_sharding_param   VARCHAR2(20),
    executor_fail_retry_count NUMBER(11)     DEFAULT 0 NOT NULL,
    trigger_time              DATE,
    trigger_code              NUMBER(11)     NOT NULL,
    trigger_msg               CLOB,
    handle_time               DATE,
    handle_code               NUMBER(11)     NOT NULL,
    handle_msg                CLOB,
    alarm_status              NUMBER(4)      DEFAULT 0 NOT NULL,
    PRIMARY KEY (id)
);

CREATE INDEX I_trigger_time ON xxl_job_log (trigger_time);
CREATE INDEX I_handle_code ON xxl_job_log (handle_code);
CREATE INDEX I_jobid_jobgroup ON xxl_job_log (job_id, job_group);
CREATE INDEX I_job_id ON xxl_job_log (job_id);

COMMENT ON TABLE xxl_job_log IS '调度日志';
COMMENT ON COLUMN xxl_job_log.id IS '调度主键ID';
COMMENT ON COLUMN xxl_job_log.job_group IS '执行器主键ID';
COMMENT ON COLUMN xxl_job_log.job_id IS '任务，主键ID';
COMMENT ON COLUMN xxl_job_log.executor_address IS '执行器地址，本次执行的地址';
COMMENT ON COLUMN xxl_job_log.executor_handler IS '执行器任务handler';
COMMENT ON COLUMN xxl_job_log.executor_param IS '执行器任务参数';
COMMENT ON COLUMN xxl_job_log.executor_sharding_param IS '执行器任务分片参数，格式如 1/2';
COMMENT ON COLUMN xxl_job_log.executor_fail_retry_count IS '失败重试次数';
COMMENT ON COLUMN xxl_job_log.trigger_time IS '调度-时间';
COMMENT ON COLUMN xxl_job_log.trigger_code IS '调度-结果';
COMMENT ON COLUMN xxl_job_log.trigger_msg IS '调度-日志';
COMMENT ON COLUMN xxl_job_log.handle_time IS '执行-时间';
COMMENT ON COLUMN xxl_job_log.handle_code IS '执行-状态';
COMMENT ON COLUMN xxl_job_log.handle_msg IS '执行-日志';
COMMENT ON COLUMN xxl_job_log.alarm_status IS '告警状态：0-默认、1-无需告警、2-告警成功、3-告警失败';

CREATE TABLE xxl_job_log_report
(
    id            NUMBER(11)   GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
